export const GLYPH_W = 5;
export const GLYPH_H = 7;
const TRACKING = 1; // blank columns between glyphs

/** Advance width of a string, in font units (multiply by scale for px). */
export function textWidth(str) {
  const n = [...str].length;
  return n === 0 ? 0 : n * (GLYPH_W + TRACKING) - TRACKING;
}

/**
 * Emit a string as SVG <rect> runs. Horizontally adjacent lit pixels are
 * merged into one rect, which roughly halves the byte count.
 *
 * @param {string} str   text to draw (lowercase is upcased)
 * @param {object} opts  { x, y, scale, fill, shadow, shadowOffset }
 */
export function text(str, { x = 0, y = 0, scale = 2, fill = '#ffffff', shadow = null, shadowOffset = scale } = {}) {
  const chars = [...str.toUpperCase()];
  const draw = (dx, dy, colour) => {
    const parts = [];
    chars.forEach((ch, i) => {
      const rows = G[ch] ?? G['?'];
      const ox = x + dx + i * (GLYPH_W + TRACKING) * scale;
      rows.forEach((row, r) => {
        let run = 0;
        for (let c = 0; c <= GLYPH_W; c++) {
          if (row[c] === '1') { run++; continue; }
          if (run > 0) {
            parts.push(
              `<rect x="${ox + (c - run) * scale}" y="${y + dy + r * scale}" ` +
              `width="${run * scale}" height="${scale}" fill="${colour}"/>`
            );
            run = 0;
          }
        }
      });
    });
    return parts.join('');
  };

  // Shadow first so the face sits on top of it.
  return (shadow ? draw(shadowOffset, shadowOffset, shadow) : '') + draw(0, 0, fill);
}
